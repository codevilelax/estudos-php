<?php

// Exercício 27: Flexões (primeiro for)
// Use um loop for para contar as flexões de 1 até 10.
// Cada número aparece em uma linha.
// Quando o loop terminar, mostre "Treino concluído!".
//
// Saída esperada:
// 1
// 2
// 3
// (...)
// 10
// Treino concluído!

for ($n = 1; $n <= 10; $n = $n + 1) {
    echo $n . "\n";
}
echo "Treino concluído!";